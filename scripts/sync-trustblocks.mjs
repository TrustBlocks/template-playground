#!/usr/bin/env node
// Brings Trustblocks into the playground from a trustblocks-templates
// checkout (github.com/TrustBlocks/trustblocks-templates), at the commit
// named in trustblocks.json:
//
//   src/samples/trustblocks.generated.ts   every template as a sample -- its
//                                          model, text, data, Clojure logic,
//                                          lifecycle and request -- and the
//                                          shared models the templates import,
//                                          to bundle beside Accord's
//   public/trustblocks-logic.js            the clause runtime, compiled for the
//                                          browser (built there by
//                                          `bb logic-bundle`); what the logic
//                                          sandbox runs
//
// Usage: node scripts/sync-trustblocks.mjs [path to trustblocks-templates]
//        (default ../trustblocks-templates)
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "../trustblocks-templates";
const { templatesRef } = JSON.parse(readFileSync("trustblocks.json", "utf8"));

const head = execFileSync("git", ["-C", dir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (head !== templatesRef) {
  console.warn(`warning: ${dir} is at ${head}, not trustblocks.json's templatesRef ${templatesRef}`);
}

const read = (...p) => readFileSync(join(dir, ...p), "utf8");
const json = (...p) => JSON.parse(read(...p));
const exists = (...p) => existsSync(join(dir, ...p));

// ---------------------------------------------------------------- templates

// Directories only -- a checkout may hold .DS_Store and the like.
const subdirs = (...p) =>
  readdirSync(join(dir, ...p), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);

const templateDirs = [
  ...subdirs("templates").map((t) => join("templates", t)),
  ...subdirs("packages").filter((p) => exists("packages", p, "templates")).flatMap((p) =>
    subdirs("packages", p, "templates").map((t) => join("packages", p, "templates", t))),
].filter((d) => exists(d, "package.json"));

const title = (name) =>
  name.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

// A template with a lifecycle and no request.json of its own (the vendor
// form) starts with the event its lifecycle begins with.
const firstEvent = (model, lifecycle) => {
  const ns = model.match(/^\s*namespace\s+(\S+)/m)[1];
  const t = lifecycle.transitions.find((t) => t.from.length === 0);
  return { $class: `${ns}.${t.event}` };
};

const samples = templateDirs.map((d) => {
  const pkg = json(d, "package.json");
  const tb = pkg.trustblocks ?? {};
  return {
    NAME: `Trustblocks · ${title(pkg.name)}`,
    DESCRIPTION: pkg.description,
    MODEL: read(d, "model", "model.cto"),
    TEMPLATE: read(d, "text", "grammar.tem.md"),
    DATA: json(d, "sample.json"),
    ...(tb.logic ? { LOGIC: read(d, tb.logic) } : {}),
    ...(tb.lifecycle ? { LIFECYCLE: json(d, tb.lifecycle) } : {}),
    ...(exists(d, "request.json")
      ? { REQUEST: json(d, "request.json") }
      : tb.lifecycle
        ? { REQUEST: firstEvent(read(d, "model", "model.cto"), json(d, tb.lifecycle)) }
        : {}),
  };
});
// The ones that run first: logic, then a lifecycle alone, then text only.
const rank = (s) => (s.LOGIC ? 0 : s.LIFECYCLE ? 1 : 2);
samples.sort((a, b) => rank(a) - rank(b) || a.NAME.localeCompare(b.NAME));

// ------------------------------------------------------------ shared models

// What the templates import beside Accord's own bundled models: the shared
// Trustblocks models, and any models.accordproject.org model a template
// keeps a copy of that the playground does not already bundle.
const accordBundled = readFileSync("src/utils/modelCache.ts", "utf8");
const models = new Map();
const addModel = (fileName, source) => {
  const namespace = source.match(/^\s*namespace\s+(\S+)/m)?.[1];
  if (namespace && !models.has(namespace) && !accordBundled.includes(`"${namespace}"`)) {
    models.set(namespace, { namespace, fileName, source });
  }
};
for (const f of ["agreement.cto", "attestation.cto"]) addModel(f, read("shared", "model", f));
for (const d of templateDirs) {
  for (const f of readdirSync(join(dir, d, "model"))) {
    if (f.startsWith("@models.accordproject.org")) addModel(f, read(d, "model", f));
  }
}

// ------------------------------------------------------------------- write

writeFileSync("src/samples/trustblocks.generated.ts", `// Generated by scripts/sync-trustblocks.mjs from trustblocks-templates@${head}.
// Do not edit: change the templates there, move trustblocks.json's
// templatesRef, and run the script again.
/* eslint-disable */
import type { Sample } from "./index";

export const TRUSTBLOCKS_TEMPLATES_REF = ${JSON.stringify(head)};

export const TRUSTBLOCKS_SAMPLES: Array<Sample> = ${JSON.stringify(samples, null, 2)};

export const TRUSTBLOCKS_BUNDLED_MODELS: Array<{ namespace: string; fileName: string; source: string }> =
  ${JSON.stringify([...models.values()], null, 2)};
`);

const bundle = join(dir, "target", "trustblocks-logic.js");
if (!existsSync(bundle)) {
  console.error(`error: ${bundle} is missing -- run \`bb logic-bundle\` in ${dir} first`);
  process.exit(1);
}
copyFileSync(bundle, "public/trustblocks-logic.js");

console.log(`${samples.length} samples, ${models.size} shared models, and trustblocks-logic.js from trustblocks-templates@${head.slice(0, 7)}`);
